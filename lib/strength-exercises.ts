export function getStrengthProgram(programId: string): StrengthProgram {
  return strengthPrograms.find((program) => program.id === programId) ?? strengthPrograms[0];
}

export function getStrengthProgramForPhase(phase: number, isTaper = false): StrengthProgram {
  if (isTaper) return getStrengthProgram('taper-maintenance');
  if (phase <= 1) return getStrengthProgram('base-strength');
  if (phase === 2) return getStrengthProgram('quality-strength');
  if (phase === 3) return getStrengthProgram('power-maintenance');
  return getStrengthProgram('quality-strength');
}
