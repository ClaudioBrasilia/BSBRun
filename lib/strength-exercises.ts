export interface StrengthProgram {
  id: string;
  name: string;
  description: string;
  duration: string;
  frequency: string;
  exercises: Exercise[];
  phase: string;
  goal: 'base' | 'quality' | 'power' | 'taper' | 'recovery' | 'prevention';
  guidance: string;
}

const byId = (id: string) => {
  const found = strengthExercises.find((item) => item.id === id);
  if (!found) throw new Error(`Exercício de força não encontrado: ${id}`);
  return found;
};

